#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md for everything linked into the app bundle.

The app binary links pusmogo-core with the `whisper` feature and the bundle
ships pusmogo-mcp. This script asks cargo for both dependency trees, reads
each crate's licence file from the local cargo registry, and adds the
whisper.cpp/ggml licence (vendored inside whisper-rs-sys) and the SQLite
public-domain note (vendored inside libsqlite3-sys).

Usage: scripts/make-notices.py [--check]
  --check  exit 1 if the committed file differs from what would be written.
"""
import argparse
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = os.path.join(ROOT, "core")
OUT = os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")

# For dual-licensed crates we take the first file found in this order; MIT
# carries the copyright line and is short, Apache-2.0 is in LICENSE already.
PREFERRED = ["LICENSE-MIT", "LICENSE-MIT.md", "LICENSE", "LICENSE.md", "license",
             "LICENSE-ZLIB", "UNLICENSE", "LICENSE-APACHE", "COPYING"]


def tree(args):
    out = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--prefix", "none", "--offline"] + args,
        cwd=CORE, check=True, capture_output=True, text=True).stdout
    crates = set()
    for line in out.splitlines():
        parts = line.replace(" (*)", "").split()
        if len(parts) >= 2 and not parts[0].startswith("pusmogo-"):
            crates.add((parts[0], parts[1].lstrip("v")))
    return crates


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--offline",
         "--features", "pusmogo-core/whisper"],
        cwd=CORE, check=True, capture_output=True, text=True).stdout
    return {(p["name"], p["version"]): p for p in json.loads(out)["packages"]}


def licence_text(pkg_dir):
    names = os.listdir(pkg_dir)
    for want in PREFERRED:
        for n in names:
            if n == want:
                with open(os.path.join(pkg_dir, n), encoding="utf-8") as f:
                    return n, f.read().strip()
    return None, None


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 epilog=__doc__.split("\n\n", 1)[1],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed file differs from what would be written")
    args = ap.parse_args()
    crates = sorted(tree(["-p", "pusmogo-core", "--features", "whisper"])
                    | tree(["-p", "pusmogo-mcp"]))
    meta = metadata()
    parts = [
        "# Third-party notices",
        "",
        "Pusmogo is licensed under Apache-2.0 (see LICENSE and NOTICE). The app",
        "bundle also contains the following third-party code, each under its own",
        "licence. Generated by `scripts/make-notices.py`; do not edit by hand.",
        "",
        "Speech models are not part of the app; they are downloaded on first use",
        "and keep their own licences (OpenAI Whisper: MIT; Silero VAD: MIT).",
        "",
        "## Summary",
        "",
        "| Component | Version | Licence |",
        "|---|---|---|",
        "| whisper.cpp and ggml (vendored in whisper-rs-sys) | bundled | MIT |",
        "| SQLite (vendored in libsqlite3-sys) | bundled | Public domain |",
        "| Sparkle (framework) | 2.10.1 | MIT and others, see below |",
        "| Magyar Ispell Hungarian dictionary (converted) | 1.9 | MPL-2.0 |",
    ]
    for name, ver in crates:
        parts.append(f"| {name} | {ver} | {meta[(name, ver)]['license']} |")
    parts.append("")

    ws = os.path.dirname(meta[("whisper-rs-sys", next(v for n, v in crates if n == "whisper-rs-sys"))]["manifest_path"])
    with open(os.path.join(ws, "whisper.cpp", "LICENSE"), encoding="utf-8") as f:
        parts += ["## whisper.cpp and ggml", "", "```", f.read().strip(), "```", ""]
    parts += ["## SQLite", "",
              "SQLite is in the public domain: https://www.sqlite.org/copyright.html", ""]

    with open(os.path.join(ROOT, "docs", "licences", "sparkle-2.10.1.txt"), encoding="utf-8") as f:
        parts += ["## Sparkle 2.10.1", "", "```", f.read().strip(), "```", ""]
    parts += ["## Magyar Ispell Hungarian dictionary", "",
              "Copyright 2025 Németh László and Godó Ferenc. Offered under MPL-2.0 or LGPL-3.0+;",
              "used here under the Mozilla Public License 2.0: https://mozilla.org/MPL/2.0/",
              "",
              "The app holds a converted copy (flags renumbered, morphology, suggestion tables",
              "and comments dropped). The converted files are `core/crates/pusmogo-core/data/`,",
              "the converter is `scripts/make-spell-dict.py`, and the original is",
              "https://github.com/LibreOffice/dictionaries/tree/master/hu_HU (project page:",
              "http://magyarispell.sf.net).", ""]

    missing = []
    for name, ver in crates:
        pkg = meta[(name, ver)]
        fname, text = licence_text(os.path.dirname(pkg["manifest_path"]))
        parts += [f"## {name} {ver}", "", f"Licence: {pkg['license']}", ""]
        if text is None:
            missing.append(name)
            parts += ["No licence file in the published crate; the licence above",
                      "is the one declared in its Cargo.toml.", ""]
        elif fname == "LICENSE-APACHE" or text.lstrip().startswith("Apache License"):
            parts += ["The Apache License 2.0 text is in this project's LICENSE file.", ""]
        else:
            parts += ["```", text, "```", ""]

    body = "\n".join(parts)
    if args.check:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != body:
                print("THIRD_PARTY_NOTICES.md is out of date: run scripts/make-notices.py", file=sys.stderr)
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"wrote {OUT}: {len(crates)} crates" + (f", no licence file: {', '.join(missing)}" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
